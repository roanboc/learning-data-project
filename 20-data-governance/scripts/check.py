"""Checks data governance's own files, and writes its matrices.

- 9-information-assets/information-assets.yml: every owner is in 2-owners/owners.yml, every glossary term
  is in 1-glossary/business-glossary.yml (or says none, and why) and owned there by the asset owner's area,
  the area that answers for the data, so its words and its data have one owner; every data object is on the enterprise
  architecture's map (UNI.DOBJ<n>.<n>, in ../10-enterprise-architecture/architecture/3_information/), every
  enterprise contract is a file in 5-data-contracts/ and every data product a file in 4-data-products/.
- 11-metrics/*.ossie.yaml: every metric document is valid Apache Ossie 0.1.1 (7-standards/), names each
  metric once across all documents, and every metric's owner is named in its description.
- 10-matrices/: the matrices, generated from the assets and the products. Don't edit them.

It reads the enterprise architecture's map, never the data project: links point one way, from the data
project to governance and from governance to the architecture. The data project checks itself against
these files (30-data-project/scripts/check/from_governance.py).

    python scripts/check.py           # check, and write 10-matrices/
    python scripts/check.py --check   # check, and fail if a matrix is out of date (CI)
"""
import argparse
import json
import re
import sys
from pathlib import Path

import jsonschema
import yaml

ROOT = Path(__file__).resolve().parents[1]
MAP = ROOT.parent / "10-enterprise-architecture" / "architecture" / "3_information"
ASSETS = ROOT / "9-information-assets" / "information-assets.yml"
MATRICES = ROOT / "10-matrices"
METRICS = ROOT / "11-metrics"
OSSIE = ROOT / "7-standards" / "ossie-0.1.1.schema.json"
GENERATED = "*Generated by `scripts/check.py` from {source}. Don't edit it: change the source, then run the script.*"


def load(path):
    return yaml.safe_load(path.read_text()) or {}


def map_objects():
    """The data objects the enterprise architecture defines: the first column of its catalogues."""
    ids = set()
    for page in MAP.glob("*.md"):
        ids |= set(re.findall(r"^\| `(DOBJ[\d.]+)` \|", page.read_text(), re.M))
    return ids


def area(owner):
    """The area an owner answers for: "Ingrid Holm, HR" and "HR" are both HR's."""
    return re.sub(r", with .*$", "", str(owner)).split(", ")[-1].strip().lower()


def check_assets(problems):
    owners = {o["name"] for o in load(ROOT / "2-owners" / "owners.yml")["owners"]}
    terms = {t["term"]: t.get("owner") for t in load(ROOT / "1-glossary" / "business-glossary.yml")["terms"]}
    products = {p.stem for p in (ROOT / "4-data-products").glob("*.yml")}
    objects = map_objects()
    assets = load(ASSETS)["assets"]
    seen = set()
    for asset in assets:
        name = asset.get("name")
        where = f"9-information-assets: {name}"
        if name in seen:
            problems.append(f"{where}: named twice")
        seen.add(name)
        if asset.get("owner") not in owners:
            problems.append(f"{where}: owner {asset.get('owner')!r} isn't in 2-owners/owners.yml")
        term = str(asset.get("glossary_term", ""))
        if not term.startswith("none") and term not in terms:
            problems.append(f"{where}: {term!r} isn't a term in 1-glossary/business-glossary.yml; "
                            "name one there, or say none and who confirmed it")
        elif term in terms and area(terms[term]) != area(asset.get("owner")):
            problems.append(f"{where}: the term {term!r} is owned by {terms[term]!r} in the glossary, another area "
                            f"than the asset's owner, {asset.get('owner')!r}: the area that answers for the data owns its words too")
        obj = str(asset.get("data_object", ""))
        if not obj.startswith("UNI.") or obj[4:] not in objects:
            problems.append(f"{where}: {obj!r} isn't a data object on the enterprise architecture's map")
        contract = asset.get("enterprise_contract")
        if contract != "none" and not (ROOT / str(contract)).exists():
            problems.append(f"{where}: no contract {contract}")
        for product in asset.get("data_products") or []:
            if product not in products:
                problems.append(f"{where}: no data product {product} in 4-data-products/")
    return assets


def check_metrics(problems):
    schema = json.loads(OSSIE.read_text())
    names = {}
    for doc in sorted(METRICS.glob("*.ossie.yaml")):
        body = load(doc)
        for error in jsonschema.Draft202012Validator(schema).iter_errors(body):
            problems.append(f"11-metrics/{doc.name}: {error.message} at {'/'.join(map(str, error.absolute_path))}")
        for model in body.get("semantic_model") or []:
            for metric in model.get("metrics") or []:
                if metric["name"] in names:
                    problems.append(f"11-metrics/{doc.name}: {metric['name']} is defined in {names[metric['name']]} too")
                names[metric["name"]] = doc.name
                if "Owned by" not in metric.get("description", "") and "Owned by" not in doc.read_text().split("version:")[0] \
                        and "owned by" not in doc.read_text().split("version:")[0].lower():
                    problems.append(f"11-metrics/{doc.name}: {metric['name']} names no owner")
    return names


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def matrices(assets):
    systems = []
    for asset in assets:
        for system in [asset["recorded_first_in"], *(asset.get("copies_in") or [])]:
            if system not in systems:
                systems.append(system)
    by_system = table(["Information asset", *systems],
                      [[a["name"], *("C" if s == a["recorded_first_in"] else "R" if s in (a.get("copies_in") or []) else ""
                                     for s in systems)] for a in assets])
    products = sorted({p for a in assets for p in a.get("data_products") or []})
    by_product = table(["Data product", *(a["name"] for a in assets)],
                       [[p, *("●" if p in (a.get("data_products") or []) else "" for a in assets)] for p in products])
    source = "`9-information-assets/information-assets.yml`"
    return {
        "assets-and-systems.md": "\n\n".join([
            "# Which system records each information asset", GENERATED.format(source=source),
            "**C**: the system it is first recorded in, its home. **R**: a system that keeps a copy, synced one way "
            "from its home. Every asset has one home (the principle *One home for every artifact*).", by_system]) + "\n",
        "assets-and-products.md": "\n\n".join([
            "# Which data products serve each information asset", GENERATED.format(source=source),
            "A product serves an asset when it publishes its data or an answer built from it. Each product's owner "
            "answers for the product; each asset's owner for what its data means.", by_product]) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if a matrix is out of date")
    args = parser.parse_args()
    problems = []
    assets = check_assets(problems)
    names = check_metrics(problems)
    stale = []
    for name, text in matrices(assets).items():
        target = MATRICES / name
        if args.check:
            if not target.exists() or target.read_text() != text:
                stale.append(f"10-matrices/{name}")
        else:
            target.write_text(text)
    if problems:
        print("\n".join(problems), file=sys.stderr)
    if stale:
        print("out of date: run python scripts/check.py\n" + "\n".join(stale), file=sys.stderr)
    if problems or stale:
        sys.exit(1)
    print(f"{len(assets)} information assets and {len(names)} metrics, all well formed; matrices up to date")


if __name__ == "__main__":
    main()
